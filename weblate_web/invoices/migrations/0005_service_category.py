def metadata_category(  # ruff:ignore[too-many-return-statements]  # pylint: disable=too-many-return-statements
    extra, packages, subscriptions, *, fallback=False
):
    """Keep this resolver frozen to the metadata formats present at migration time."""
    if not isinstance(extra, dict):
        return 0
    if not fallback:
        name = extra.get("package", extra.get("subscription"))
        if isinstance(name, str):
            return packages.get(name, 0)
        if "package" in extra:
            return 0
        return None
    if "subscription_upgrade" in extra:
        return 0
    if extra.get("category") == "donate" or any(
        key in extra for key in ("donation", "donation_service", "reward")
    ):
        return 4
    plan = extra.get("plan")
    if isinstance(plan, int) and not isinstance(plan, bool) and plan > 0:
        return 20
    if isinstance(plan, str):
        return packages.get(plan, 0)
    subscription = extra.get("subscription")
    if isinstance(subscription, int) and not isinstance(subscription, bool):
        return subscriptions.get(subscription, 0)
    return None


def backfill_invoice_categories(apps, schema_editor) -> None:
    alias = schema_editor.connection.alias
    Package = apps.get_model("weblate_web", "Package")
    Subscription = apps.get_model("weblate_web", "Subscription")
    Invoice = apps.get_model("invoices", "Invoice")
    packages_by_id = dict(Package.objects.using(alias).values_list("pk", "category"))
    packages = dict(Package.objects.using(alias).values_list("name", "category"))
    subscriptions = dict(
        Subscription.objects.using(alias).values_list("pk", "package__category")
    )
    invoices = (
        Invoice.objects.using(alias)
        .filter(category=1, correction_of__isnull=True)
        .prefetch_related("invoiceitem_set", "paid_payment_set", "draft_payment_set")
    )
    for invoice in invoices.iterator(chunk_size=500):
        items = list(invoice.invoiceitem_set.all())
        linked = {
            packages_by_id.get(item.package_id, 0)
            for item in items
            if item.package_id is not None
        }
        # Mixed items cannot be represented by a single invoice category.
        if len(linked) > 1 or 0 in linked:
            continue
        if items and all(item.package_id is not None for item in items):
            category = linked.pop()
        else:
            payment_metadata = [
                payment.extra
                for payment in (
                    *invoice.paid_payment_set.all(),
                    *invoice.draft_payment_set.all(),
                )
            ]
            evidence = [metadata_category(invoice.extra, packages, subscriptions)]
            if evidence == [None]:
                evidence = [
                    metadata_category(extra, packages, subscriptions)
                    for extra in payment_metadata
                ]
            if not any(value is not None for value in evidence):
                evidence = [
                    metadata_category(extra, packages, subscriptions, fallback=True)
                    for extra in (invoice.extra, *payment_metadata)
                ]
            categories = {value for value in evidence if value is not None}
            if len(categories) != 1 or 0 in categories:
                continue
            category = categories.pop()
            if linked and linked != {category}:
                continue
        Invoice.objects.using(alias).filter(pk=invoice.pk).update(category=category)

    # Credit notes have no package metadata; follow the original after backfilling it.
    corrections = (
        Invoice.objects.using(alias)
        .filter(category=1, correction_of__isnull=False)
        .values_list("pk", "correction_of__category")
    )
    for pk, category in corrections.iterator(chunk_size=500):
        Invoice.objects.using(alias).filter(pk=pk).update(category=category)


